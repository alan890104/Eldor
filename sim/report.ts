function typeChart(): string {
  const list = ELEMENT_ORDER;
  const cell = (m: number) => (m > 1 ? `**${m}**` : m < 1 ? `*${m}*` : '-');
  return table(
    ['Attacker / Defender', ...list.map((e) => ELEMENT_NAME[e])],
    list.map((a) => [`**${ELEMENT_NAME[a]}**`, ...list.map((d) => cell(singleTypeMultiplier(a, d)))]),
  );
}

function growthTable(): string {
  const sp = SPIRITS.find((s) => s.id === 'pyre_dragoon')!;
  const points: [number, Stage][] = [
    [1, 1],
    [10, 1],
    [20, 1],
    [20, 2],
    [30, 2],
    [40, 2],
    [40, 3],
    [50, 3],
    [60, 3],
  ];
  return table(
    ['Level', 'Stage', ...STAT_KEYS.map((k) => STAT_NAME[k])],
    points.map(([lv, stage]) => {
      const st = computeStats(sp.base, lv, stage);
      return [lv, ['', 'I', 'II', 'III'][stage], ...STAT_KEYS.map((k) => st[k])];
    }),
  );
}

function workedExample(): string {
  const atk = SPIRITS.find((s) => s.id === 'pyre_dragoon')!;
  const def = SPIRITS.find((s) => s.id === 'elderwood_warden')!;
  const s = SKILL_BY_ID.get('blaze_slash') ?? representativeAttack(atk);
  const a = statsAtMax(atk.base);
  const d = statsAtMax(def.base);
  const k = defenseConstant(MAX_LEVEL);
  const df = defenseFactor(d.def, MAX_LEVEL);
  const tm = typeMultiplier(s.element, def.elements);
  const dmg = computeDamage({
    attack: a.atk,
    defense: d.def,
    power: s.power,
    attackerLevel: MAX_LEVEL,
    typeMult: tm,
    stab: true,
  });
  const crit = computeDamage({
    attack: a.atk,
    defense: d.def,
    power: s.power,
    attackerLevel: MAX_LEVEL,
    typeMult: tm,
    stab: true,
    crit: true,
  });
  const buffed = computeDamage({
    attack: a.atk * statStageMultiplier(2),
    defense: d.def,
    power: s.power,
    attackerLevel: MAX_LEVEL,
    typeMult: tm,
    stab: true,
    fieldMult: 1.3,
  });
  return [
    `**${nameOf(atk)}** (Lv 60, Attack ${a.atk}) uses **${nameOf(s)}** (power ${s.power}) on **${nameOf(def)}** (Lv 60, Defense ${d.def}, HP ${d.hp}):`,
    '',
    '```',
    `Base           = Attack ${a.atk} × power ${s.power}/100                              = ${(a.atk * s.power / 100).toFixed(1)}`,
    `Defense factor = K / (K + Defense) = ${k} / (${k} + ${d.def})                  = ${df.toFixed(3)}`,
    `Element        = Fire → Nature effective ×${tm}, same-element bonus ×${STAB}  = ×${(tm * STAB).toFixed(2)}`,
    `Damage         = ${(a.atk * s.power / 100).toFixed(1)} × ${df.toFixed(3)} × ${(tm * STAB).toFixed(2)}                                   = ${dmg} (${pct(dmg / d.hp)} of the foe's HP)`,
    `On crit        = ${crit} (${pct(crit / d.hp)})`,
    `Attack +2 stages under Blazing Sun (Fire ×1.3) = ${buffed} (${pct(buffed / d.hp)})`,
    '```',
  ].join('\n');
}

function durabilityTable(): string {
  const phys = basicAttack('physical', 110);
  const mag = basicAttack('magic', 110);
  const std = { base: STANDARD_BASE, elements: ['neutral'] as Element[] };
  const rows = [...SPIRITS]
    .map((sp) => {
      const p = hit(std, sp, phys);
      const m = hit(std, sp, mag);
      return { sp, p, m };
    })
    .sort((x, y) => x.p.percent + x.m.percent - (y.p.percent + y.m.percent));
  return table(
    ['Spirit', 'Rarity', 'Physical hit %HP', 'Hits to KO', 'Magic hit %HP', 'Hits to KO'],
    rows.map(({ sp, p, m }) => [
      nameOf(sp),
      sp.rarity,
      pct(p.percent),
      p.hitsToKo,
      pct(m.percent),
      m.hitsToKo,
    ]),
  );
}

function offenseTable(): string {
  const std = { base: STANDARD_BASE, elements: ['neutral'] as Element[] };
  const rows = SPIRITS.map((sp) => {
    const s = representativeAttack(sp);
    return { sp, s, h: hit(sp, std, s) };
  }).sort((a, b) => b.h.percent - a.h.percent);
  return table(
    ['Spirit', 'Rarity', 'Representative skill', 'Cost', '%HP vs standard spirit', 'Hits to KO'],
    rows.map(({ sp, s, h }) => [nameOf(sp), sp.rarity, nameOf(s), s.cost, pct(h.percent), h.hitsToKo]),
  );
}

function matchupMatrix(ids: string[]): string {
  const list = ids.map((id) => SPIRITS.find((s) => s.id === id)!);
  return table(
    ['Attacker / Defender', ...list.map((s) => shortName(s))],
    list.map((a) => {
      const s = representativeAttack(a);
      return [
        `**${shortName(a)}**<br><sub>${nameOf(s)}</sub>`,
        ...list.map((d) => {
          const h = hit(a, d, s);
          return `${h.hitsToKo} (${pct(h.percent, 0)})`;
        }),
      ];
    }),
  );
}

function speedTable(): string {
  const rows = [...SPIRITS]
    .map((sp) => ({ sp, spd: statsAtMax(sp.base).spd }))
    .sort((a, b) => b.spd - a.spd);
  return table(
    ['Speed', 'Spirits'],
    groupBy(rows, (r) => r.spd).map(([spd, rs]) => [spd, rs.map((r) => nameOf(r.sp)).join(', ')]),
  );
}

function groupBy<T, K>(list: T[], key: (t: T) => K): [K, T[]][] {
  const m = new Map<K, T[]>();
  for (const t of list) {
    const k = key(t);
    m.set(k, [...(m.get(k) ?? []), t]);
  }
  return [...m.entries()];
}

function gachaSection(): string {
  const cfg = LIMITED_BANNER;
  const one = firstSsrDistribution(cfg);
  const feat = featuredDistribution(cfg);
  const lr = longRunRates(cfg);
  const lines: string[] = [];
  lines.push(
    table(
      ['Item', 'Value'],
      [
        ['Base SSR rate', pct(cfg.ssrBase)],
        ['Base SR rate', pct(cfg.srBase)],
        ['Soft pity', `From pull ${cfg.softPityStart} since the last SSR, the SSR rate rises by ${pct(cfg.softPityStep, 0)} per pull`],
        ['Hard pity', `An SSR is guaranteed on pull ${cfg.hardPity}`],
        ['SR pity', `At least 1 SR or better every ${cfg.srPity} pulls`],
        ['Rate-up', `${pct(cfg.featuredShare, 0)} of SSRs are the rate-up; after a miss, the next SSR is guaranteed to be the rate-up`],
        ['**Combined SSR rate**', `**${pct(lr.ssr, 2)}**`],
        ['**Combined SR rate**', `**${pct(lr.sr, 2)}**`],
        ['Combined R rate', pct(lr.r, 2)],
      ],
    ),
    '',
  );
  lines.push(
    table(
      ['', 'Mean', 'Median', '90% of players', '99% of players', 'Worst case'],
      [
        ['Getting any SSR', mean(one).toFixed(1), quantile(one, 0.5), quantile(one, 0.9), quantile(one, 0.99), cfg.hardPity],
        ['Getting the rate-up SSR', mean(feat).toFixed(1), quantile(feat, 0.5), quantile(feat, 0.9), quantile(feat, 0.99), cfg.hardPity * 2],
      ],
    ),
    '',
  );
  lines.push('**Chance of the rate-up SSR within N pulls (starting from zero)**', '');
  // From 10 pulls up to twice the hard pity, split evenly into about 10 columns
  const step = Math.max(10, Math.round((cfg.hardPity * 2) / 10 / 10) * 10);
  const ns = Array.from({ length: Math.ceil((cfg.hardPity * 2) / step) }, (_, i) => Math.min(cfg.hardPity * 2, (i + 1) * step));
  const prob = (p: number) => (p >= 1 - 1e-9 ? '100%' : p > 0.995 ? '>99.5%' : pct(p, 0));
  lines.push(table(['Pulls', ...ns.map(String)], [['Chance', ...ns.map((n) => prob(cdf(feat, n)))]]), '');
  lines.push('**SSR chance per pull (pull n since the last SSR)**', '');
  const s0 = cfg.softPityStart;
  const ks = [...new Set([1, s0 - 1, s0, s0 + 1, s0 + 2, s0 + 4, Math.round((s0 + cfg.hardPity) / 2), cfg.hardPity - 1, cfg.hardPity])].filter((n) => n >= 1 && n <= cfg.hardPity);
  lines.push(table(['Pull n', ...ks.map(String)], [['Chance', ...ks.map((n) => pct(ssrRateAt(n, cfg)))]]), '');
  return lines.join('\n');
}

function expSection(): string {
  const levels = [1, 5, 10, 15, 19, 20, 30, 39, 40, 50, 59];
  return table(
    ['Level', 'EXP to next level', 'Total EXP', 'EXP from a same-level wild spirit', 'Battles needed'],
    levels.map((lv) => {
      const need = expToNext(lv);
      const gain = battleExp(lv, lv);
      return [lv, need, totalExpTo(lv), gain, (need / gain).toFixed(1)];
    }),
  ) + `\n\nReaching Lv ${MAX_LEVEL} takes **${totalExpTo(MAX_LEVEL).toLocaleString('en-US')}** EXP in total.`;
}

function captureSection(): string {
  const hps = [1, 0.5, 0.25, 0.05];
  const lines: string[] = [];
  for (const rarity of ['N', 'R', 'SR'] as const) {
    lines.push(
      `**${rarity}**`,
      '',
      table(
        ['HP left', 'Basic Pact Stone', 'Basic + control status', 'Advanced Pact Stone', 'Master Pact Stone'],
        hps.map((hp) => [
          pct(hp, 0),
          pct(captureChance(rarity, hp, 'basic', 'none'), 0),
          pct(captureChance(rarity, hp, 'basic', 'control'), 0),
          pct(captureChance(rarity, hp, 'advanced', 'none'), 0),
          pct(captureChance(rarity, hp, 'master', 'none'), 0),
        ]),
      ),
      '',
    );
  }
  return lines.join('\n');
}

function aetherSection(): string {
  const turns = [1, 2, 3, 4, 5];
  return (
    table(['Turn', ...turns.map(String)], [['Aether available (if all is saved)', ...turns.map(aetherAtTurnStart)]]) +
    `\n\nStarts at ${AETHER.start}, +${AETHER.perTurn} at the start of each turn, capped at ${AETHER.max}.`
  );
}

function rarityBstTable(): string {
  const rows = groupBy(SPIRITS, (s) => s.rarity).map(([r, list]) => [
    r,
    list.length,
    [...new Set(list.map((s) => bst(s.base)))].join(', '),
  ]);
  return table(['Rarity', 'Count', 'BST'], rows);
}

function balanceDoc(): string {
  const lines: string[] = ['# Balance Report', '', HEADER];
  lines.push('## 1. Element Matchup Chart', '', 'Bold = effective (×1.5), italic = resisted (×0.75), - = ×1.', '', typeChart(), '');
  lines.push('## 2. Rarity and Base Stats', '', rarityBstTable(), '');
  lines.push('## 3. Growth Curve Example (Pyre Dragoon)', '', growthTable(), '');
  lines.push('## 4. Damage Calculation Example', '', workedExample(), '');
  lines.push(
    '## 5. Durability: Taking a Standard Attack',
    '',
    'The attacker is a "standard spirit" (every base stat 80, Lv 60) using a 110-power, same-element attack with no matchup advantage.',
    '',
    durabilityTable(),
    '',
  );
  lines.push(
    '## 6. Offense: Representative Skill vs the Standard Spirit',
    '',
    'Representative skill = the attack with the highest expected damage among the learnable skills that cost 2 or less and share the spirit\'s element. The foe is the "standard spirit" (Neutral).',
    '',
    offenseTable(),
    '',
  );
  lines.push(
    '## 7. Matchup Matrix: The Eight Sacred Spirits',
    '',
    'Each cell is the number of hits the attacker\'s representative skill needs to KO the defender (%HP per hit).',
    '',
    matchupMatrix(['ignisar', 'thalassene', 'sylvaron', 'aeroth', 'terragon', 'voltarion', 'luminael', 'noxfang']),
    '',
  );
  lines.push(
    '## 8. Matchup Matrix: Starting Partner (Eldarin), the Rival\'s Pyre Dragoon and Common Spirits',
    '',
    matchupMatrix(['eldarin', 'pyre_dragoon', 'oathsea_sage', 'elderwood_warden', 'skyreign', 'monolith', 'stormram', 'eclipse_batlord', 'relic_blade']),
    '',
  );
  lines.push('## 9. Speed Ranking (Lv 60)', '', speedTable(), '');
  lines.push('## 10. Aether', '', aetherSection(), '');
  lines.push('## 11. Star Gate Summon Rates', '', gachaSection());
  lines.push('## 12. Experience Curve', '', expSection(), '');
  lines.push('## 13. Capture Rates', '', captureSection());
  return lines.join('\n');
}

