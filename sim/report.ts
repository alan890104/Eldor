const out = new URL('../docs/catalog/', import.meta.url);
const HEADER = '> This file is generated by `npm run report` from `data/*.json` and `sim/*.ts`. Do not edit it by hand.\n';

const CATEGORY_LABEL: Record<SkillDef['category'], string> = {
  physical: 'Physical',
  magic: 'Magic',
  status: 'Status',
  trap: 'Trap',
  ultimate: 'Ultimate',
};
const TRAP_SPEED_LABEL = { normal: 'Normal', quick: 'Quick', counter: 'Counter' } as const;
const DAMAGE_TYPE_LABEL = { physical: 'Physical', magic: 'Magic', auto: 'Higher of the two' } as const;

// formulas.ts keeps the Chinese labels the game shows, so the catalog has its own English element and stat names
const ELEMENT_NAME: Record<Element, string> = {
  water: 'Water',
  fire: 'Fire',
  nature: 'Nature',
  wind: 'Wind',
  earth: 'Earth',
  thunder: 'Thunder',
  light: 'Light',
  dark: 'Dark',
  neutral: 'Neutral',
};
const STAT_NAME: Record<StatKey, string> = { hp: 'HP', atk: 'Attack', mag: 'Magic Power', def: 'Defense', res: 'Resistance', spd: 'Speed' };
/** A spirit's or skill's name in the catalog: the English name, or the Chinese one when a record has none */
const nameOf = (r: { name: string; en?: string }) => r.en || r.name;
/** The short form for matrix headers: 'Ignisar, the Blazing King' becomes 'Ignisar', and a Chinese name is cut at its katakana dot */
const shortName = (r: { name: string; en?: string }) => nameOf(r).split(/[,\u30fb]/)[0];

const pct = (x: number, digits = 1) => `${(x * 100).toFixed(digits)}%`;
const els = (e: readonly Element[]) => e.map((x) => ELEMENT_NAME[x]).join(' / ');
const row = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;
const table = (head: string[], rows: (string | number)[][], align?: string[]) =>
  [row(head), row(align ?? head.map(() => '---')), ...rows.map(row)].join('\n');

function learners(): Map<string, string[]> {
  const m = new Map<string, string[]>();
  for (const sp of SPIRITS) {
    for (const id of [...new Set([...sp.learnset.map((e) => e.id), sp.ultimate])]) {
      const list = m.get(id) ?? [];
      list.push(nameOf(sp));
      m.set(id, list);
    }
  }
  return m;
}

function powerText(s: SkillDef): string {
  if (s.power === 0) return 'None';
  const hits = s.tags.hits;
  return hits ? `${s.power / hits}×${hits}` : String(s.power);
}

function skillTypeText(s: SkillDef): string {
  if (s.category === 'trap') return `Trap (${TRAP_SPEED_LABEL[s.trapSpeed ?? 'normal']})`;
  if (s.category === 'ultimate') return `Ultimate (${DAMAGE_TYPE_LABEL[s.damageType ?? 'auto']})`;
  return CATEGORY_LABEL[s.category];
}

function skillEffectText(s: SkillDef): string {
  const text = s.trigger ? `**Trigger: ${s.trigger}.** ${s.text}` : s.text;
  return s.basic ? `${text} (basic)` : s.exclusive ? `${text} (exclusive)` : text;
}

// ───────────────────────── Spirit Codex ─────────────────────────

function spiritsDoc(): string {
  const lines: string[] = ['# Spirit Codex', '', HEADER];
  lines.push(
    'Stats are the values at **Lv 60, Stage III, Resonance R0** (HP = base stat × 7 × 2, every other stat = base stat × 7).',
    'For roles and skills see [Skill Design](../05-skill-design.md); for formulas see [Stats and Growth](../03-growth.md).',
    '',
  );

  const rarities: SpiritDef['rarity'][] = ['SSR', 'SR', 'R', 'N'];
  const sorted = [...SPIRITS].sort(
    (a, b) => rarities.indexOf(a.rarity) - rarities.indexOf(b.rarity),
  );
  lines.push('## Overview', '');
  lines.push(
    table(
      ['Name', 'Element', 'Rarity', 'Role', 'BST', ...STAT_KEYS.map((k) => STAT_NAME[k]), 'Obtain'],
      sorted.map((sp) => {
        const st = statsAtMax(sp.base);
        return [
          `[${nameOf(sp)}](#${sp.id})`,
          els(sp.elements),
          sp.rarity,
          sp.role,
          bst(sp.base),
          ...STAT_KEYS.map((k) => st[k]),
          sp.obtain,
        ];
      }),
    ),
    '',
  );

  for (const sp of sorted) {
    lines.push(`<a id="${sp.id}"></a>`, `## ${sp.en ? `${sp.en} (${sp.name})` : sp.name}`, '');
    lines.push(`> ${sp.lore}`, '');
    lines.push(
      `- **Element**: ${els(sp.elements)} | **Rarity**: ${sp.rarity} | **Role**: ${sp.role}`,
      ...(sp.concept ? [`- **Playstyle**: ${sp.concept}`] : []),
      ...(sp.mechanic ? [`- **Signature mechanic [${sp.mechanic.name}]**: ${sp.mechanic.text}`] : []),
      `- **Trait [${sp.trait.name}]**: ${sp.trait.text}`,
      `- **Obtain**: ${sp.obtain}`,
      '',
    );
    const lv60 = statsAtMax(sp.base);
    lines.push(
      table(
        ['', ...STAT_KEYS.map((k) => STAT_NAME[k]), 'Total'],
        [
          ['Base stats', ...STAT_KEYS.map((k) => sp.base[k]), bst(sp.base)],
          ['Lv 60', ...STAT_KEYS.map((k) => lv60[k]), ''],
        ],
      ),
      '',
    );
    lines.push('**Learnable skills** (learned by level; ★ flagship skill, ◇ basic skill; the ultimate unlocks at Stage III)', '');
    lines.push(
      table(
        ['Level', 'Skill', 'Element', 'Type', 'Cost', 'Power', 'Effect'],
        [...sp.learnset.map((e) => [e.lv, e.id] as const), ['III', sp.ultimate] as const]
          .filter(([, id]) => SKILL_BY_ID.has(id))
          .map(([lv, id]) => {
            const s = skill(id);
            const mark = s.tags.sig ? '★ ' : s.basic ? '◇ ' : '';
            return [lv, mark + nameOf(s), ELEMENT_NAME[s.element], skillTypeText(s), s.cost, powerText(s), skillEffectText(s)];
          }),
      ),
      '',
    );
  }
  return lines.join('\n');
}

// ───────────────────────── Skill tables ─────────────────────────

function skillsDoc(): string {
  const who = learners();
  const lines: string[] = ['# Skill List', '', HEADER];
  lines.push(
    '- **Budget** = skill value ÷ the budget its cost earns; the allowed range is 0.85 to 1.15. For the method see [Skill Design §7](../05-skill-design.md#7-skill-budget-a-number-design-tool).',
    '- **Basic skills**: the plain skills in `data/kits/_basic.json`; spirits of the same element, or Neutral spirits, can put them in a learnset. Every other skill is exclusive. Guard is a system action and is not in the skill tables.',
    '- A blank Priority cell means 0. A blank Accuracy cell means 100.',
    '',
  );

  const groups: { title: string; filter: (s: SkillDef) => boolean }[] = [
    ...ELEMENT_ORDER.map((el) => ({
      title: `${ELEMENT_NAME[el]} skills`,
      filter: (s: SkillDef) => s.element === el && s.category !== 'ultimate' && SKILL_SOURCE.get(s.id) !== 'system',
    })),
    { title: 'Ultimates', filter: (s: SkillDef) => s.category === 'ultimate' },
  ];

  for (const g of groups) {
    const list = SKILLS.filter(g.filter);
    if (list.length === 0) continue;
    lines.push(`## ${g.title}`, '');
    lines.push(
      table(
        ['Skill', 'Element', 'Type', 'Cost', 'Power', 'Accuracy', 'Priority', 'Effect', 'Budget', 'Learned by'],
        list.map((s) => {
          const r = evaluateSkill(s);
          const learnedBy = (who.get(s.id) ?? []).join(', ') || 'None';
          return [
            `${nameOf(s)}<br><sub>${s.name}</sub>`,
            ELEMENT_NAME[s.element],
            skillTypeText(s),
            s.cost,
            powerText(s),
            s.accuracy < 100 ? s.accuracy : '',
            s.priority !== 0 ? (s.priority > 0 ? `+${s.priority}` : s.priority) : '',
            skillEffectText(s),
            r.ratio.toFixed(2),
            learnedBy,
          ];
        }),
      ),
      '',
    );
  }

  lines.push('## Budget breakdown', '', '<details><summary>Show the valuation breakdown of every skill</summary>', '');
  lines.push(
    table(
      ['Skill', 'Target', 'Value', 'Ratio', 'Breakdown'],
      SKILLS.map((s) => {
        const r = evaluateSkill(s);
        return [nameOf(s), targetBudget(s), r.value.toFixed(1), r.ratio.toFixed(2), r.parts.join('; ')];
      }),
    ),
    '',
    '</details>',
    '',
  );
  return lines.join('\n');
}

